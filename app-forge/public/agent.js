/* AI Phone sources for the AppForge generator: the Groq client with automatic
   model failover and the accessibility task runner. Kept in their own file so
   gen.js stays readable; the browser loads this with a script tag and Node with
   require('./agent.js'). */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  root.AppForgeAgent = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function groqClientKt(c) {
    return [
      'package ' + c.pkg,
      '',
      'import android.content.Context',
      'import org.json.JSONArray',
      'import org.json.JSONObject',
      'import java.net.HttpURLConnection',
      'import java.net.URL',
      '',
      '/** The Groq key lives in the phone, not in the APK source. */',
      'object Prefs {',
      '    private const val FILE = "ai_phone"',
      '    private const val KEY = "groq_key"',
      '',
      '    fun key(context: Context): String =',
      '        context.getSharedPreferences(FILE, Context.MODE_PRIVATE).getString(KEY, "").orEmpty()',
      '',
      '    fun setKey(context: Context, value: String) {',
      '        context.getSharedPreferences(FILE, Context.MODE_PRIVATE).edit().putString(KEY, value).apply()',
      '    }',
      '}',
      '',
      '/** Groq chat completions with model failover: 429 (rate limit), 413, 404',
      '    (retired model) or 5xx moves on to the next model instead of failing. */',
      'object GroqClient {',
      '    private const val CHAT_URL = "https://api.groq.com/openai/v1/chat/completions"',
      '    private const val MODELS_URL = "https://api.groq.com/openai/v1/models"',
      '    private val PREFERRED = listOf("openai/gpt-oss-120b", "openai/gpt-oss-20b", "qwen/qwen3.8-27b")',
      '',
      '    data class Reply(val ok: Boolean, val text: String, val model: String)',
      '',
      '    private class Raw(val code: Int, val body: String)',
      '',
      '    fun chat(context: Context, system: String, user: String, log: (String) -> Unit): Reply {',
      '        val key = Prefs.key(context)',
      '        if (key.isEmpty()) {',
      '            return Reply(false, "គ្មាន Groq API key — បញ្ចូលក្នុង app សិន (console.groq.com)", "")',
      '        }',
      '        val models = listModels(key)',
      '        var last = "មិនអាចហៅ Groq បាន"',
      '        for (index in models.indices) {',
      '            val model = models[index]',
      '            val raw = call(key, model, system, user)',
      '            if (raw.code == 200) {',
      '                val text = content(raw.body)',
      '                if (text.isNotEmpty()) return Reply(true, text, model)',
      '            }',
      '            last = errorOf(raw)',
      '            val next = models.getOrNull(index + 1)',
      '            if (!retryable(raw.code) || next == null) break',
      '            log("🔴 " + model + " (" + raw.code + ") → ប្តូរ " + next)',
      '        }',
      '        return Reply(false, last, "")',
      '    }',
      '',
      '    private fun retryable(code: Int): Boolean =',
      '        code == 429 || code == 413 || code == 404 || code == 500 || code == 503',
      '',
      '    private fun listModels(key: String): List<String> {',
      '        val raw = request(MODELS_URL, key, null)',
      '        if (raw.code != 200) return PREFERRED',
      '        val ids = mutableListOf<String>()',
      '        try {',
      '            val data = JSONObject(raw.body).optJSONArray("data") ?: return PREFERRED',
      '            for (i in 0 until data.length()) {',
      '                val id = data.optJSONObject(i)?.optString("id") ?: continue',
      '                val low = id.lowercase()',
      '                if (low.contains("whisper") || low.contains("tts") || low.contains("guard")) continue',
      '                if (low.contains("embed") || low.contains("orpheus")) continue',
      '                ids.add(id)',
      '            }',
      '        } catch (e: Exception) {',
      '            return PREFERRED',
      '        }',
      '        if (ids.isEmpty()) return PREFERRED',
      '        return ids.sortedWith(compareBy({ rank(it) }, { it })).take(5)',
      '    }',
      '',
      '    private fun rank(id: String): Int {',
      '        val at = PREFERRED.indexOf(id)',
      '        return if (at < 0) PREFERRED.size else at',
      '    }',
      '',
      '    private fun call(key: String, model: String, system: String, user: String): Raw {',
      '        val messages = JSONArray()',
      '        messages.put(JSONObject().put("role", "system").put("content", system))',
      '        messages.put(JSONObject().put("role", "user").put("content", user))',
      '        val payload = JSONObject()',
      '            .put("model", model)',
      '            .put("messages", messages)',
      '            .put("temperature", 0.2)',
      '            .put("max_tokens", 700)',
      '        return request(CHAT_URL, key, payload.toString())',
      '    }',
      '',
      '    private fun content(body: String): String = try {',
      '        JSONObject(body).optJSONArray("choices")?.optJSONObject(0)',
      '            ?.optJSONObject("message")?.optString("content") ?: ""',
      '    } catch (e: Exception) {',
      '        ""',
      '    }',
      '',
      '    private fun errorOf(raw: Raw): String = try {',
      '        JSONObject(raw.body).optJSONObject("error")?.optString("message") ?: ("HTTP " + raw.code)',
      '    } catch (e: Exception) {',
      '        "HTTP " + raw.code + " " + raw.body.take(120)',
      '    }',
      '',
      '    private fun request(url: String, key: String, payload: String?): Raw {',
      '        return try {',
      '            val conn = URL(url).openConnection() as HttpURLConnection',
      '            try {',
      '                conn.connectTimeout = 15000',
      '                conn.readTimeout = 45000',
      '                conn.requestMethod = if (payload == null) "GET" else "POST"',
      '                conn.setRequestProperty("Authorization", "Bearer " + key)',
      '                conn.setRequestProperty("Content-Type", "application/json")',
      '                if (payload != null) {',
      '                    conn.doOutput = true',
      '                    conn.outputStream.use { it.write(payload.toByteArray()) }',
      '                }',
      '                val code = conn.responseCode',
      '                val stream = if (code in 200..299) conn.inputStream else conn.errorStream',
      '                Raw(code, stream?.bufferedReader()?.use { it.readText() } ?: "")',
      '            } finally {',
      '                conn.disconnect()',
      '            }',
      '        } catch (e: Exception) {',
      '            Raw(0, e.message ?: "ភ្ជាប់មិនបាន")',
      '        }',
      '    }',
      '}',
      ''
    ].join('\n');
  }

  function agentRunnerKt(c) {
    return [
      'package ' + c.pkg,
      '',
      'import android.content.Context',
      'import android.content.pm.PackageManager',
      'import org.json.JSONObject',
      '',
      '/** The panel subscribes here; every agent line shows in the overlay. */',
      'object AgentLog {',
      '    @Volatile',
      '    var sink: ((String) -> Unit)? = null',
      '',
      '    fun emit(line: String) {',
      '        sink?.invoke(line)',
      '    }',
      '}',
      '',
      'data class Step(val action: String, val target: String, val count: Int)',
      '',
      '/** Turns a command into steps, then performs them with accessibility. */',
      'object AgentRunner {',
      '    @Volatile',
      '    private var busy = false',
      '',
      '    private val TIKTOK = listOf(',
      '        "com.zhiliaoapp.musically",',
      '        "com.ss.android.ugc.trill",',
      '        "com.zhiliaoapp.musically.go"',
      '    )',
      '',
      '    private const val SYSTEM_PROMPT =',
      '        "អ្នកគឺជាអ្នកបញ្ជាទូរស័ព្ទ Android។ ឆ្លើយជា JSON តែម្តង គ្មានអត្ថបទផ្សេង: " +',
      '            "{\\"steps\\":[{\\"action\\":\\"open\\",\\"target\\":\\"tiktok\\"}," +',
      '            "{\\"action\\":\\"scroll\\",\\"count\\":20}]} " +',
      '            "action មានតែ open, scroll, back, home, wait ។ target ជាឈ្មោះ app ឬ package។ " +',
      '            "count ជាចំនួនដង (1-200)។"',
      '',
      '    fun run(context: Context, command: String, log: (String) -> Unit) {',
      '        if (busy) {',
      '            log("⏳ ការងារមួយកំពុងរត់ — រង់ចាំវាចប់សិន")',
      '            return',
      '        }',
      '        busy = true',
      '        val app = context.applicationContext',
      '        Thread {',
      '            try {',
      '                execute(app, command, log)',
      '            } catch (e: Exception) {',
      '                log("✖ " + (e.message ?: "បរាជ័យ"))',
      '            } finally {',
      '                busy = false',
      '            }',
      '        }.start()',
      '    }',
      '',
      '    private fun execute(context: Context, command: String, log: (String) -> Unit) {',
      '        val service = AgentAccessibilityService.instance',
      '            ?: throw IllegalStateException("Accessibility មិនទាន់បើក — Settings › Accessibility")',
      '        val size = service.screenSize()',
      '        log("📐 អេក្រង់ " + size.first + "×" + size.second + " px")',
      '        var steps = parse(command)',
      '        if (steps.isEmpty()) {',
      '            log("🧠 សួរ AI ដើម្បីរៀបផែនការ…")',
      '            val reply = GroqClient.chat(context, SYSTEM_PROMPT, command, log)',
      '            if (!reply.ok) {',
      '                log("✖ AI: " + reply.text)',
      '                return',
      '            }',
      '            log("🤖 " + reply.model + ": " + reply.text.replace("\\n", " ").take(180))',
      '            steps = parseJson(reply.text)',
      '        }',
      '        if (steps.isEmpty()) {',
      '            log("✖ មិនយល់បញ្ជា — សាក: បើក tiktok អូស 20")',
      '            return',
      '        }',
      '        log("▶ " + steps.size + " ជំហាន")',
      '        for (step in steps) {',
      '            when (step.action) {',
      '                "open" -> {',
      '                    val pkg = resolve(context, step.target)',
      '                    if (pkg == null) {',
      '                        log("✖ រកមិនឃើញ app: " + step.target)',
      '                        return',
      '                    }',
      '                    if (!service.openApp(pkg)) {',
      '                        log("✖ បើក " + pkg + " មិនបាន")',
      '                        return',
      '                    }',
      '                    log("📱 បើក " + pkg)',
      '                    Thread.sleep(2600)',
      '                }',
      '                "scroll" -> {',
      '                    val total = step.count.coerceIn(1, 200)',
      '                    for (i in 1..total) {',
      '                        if (!service.swipeUp()) {',
      '                            log("✖ អូសមិនបាន — សិទ្ធិ gesture ត្រូវបានបដិសេធ")',
      '                            break',
      '                        }',
      '                        log("⬆ " + i + "/" + total)',
      '                        Thread.sleep(1600)',
      '                    }',
      '                }',
      '                "back" -> {',
      '                    service.back()',
      '                    Thread.sleep(700)',
      '                }',
      '                "home" -> {',
      '                    service.home()',
      '                    Thread.sleep(700)',
      '                }',
      '                "wait" -> Thread.sleep((step.count.coerceIn(1, 30) * 1000).toLong())',
      '            }',
      '        }',
      '        log("✔ ចប់")',
      '    }',
      '',
      '    private fun parse(command: String): List<Step> {',
      '        val steps = mutableListOf<Step>()',
      '        val open = Regex("""(?:open\\s*:|បើក)\\s*([A-Za-z0-9_.]+)""", RegexOption.IGNORE_CASE).find(command)',
      '        if (open != null) steps.add(Step("open", open.groupValues[1], 0))',
      '        var scroll = Regex("""(?:scroll|អូស|រំកិល|swipe)\\s*:?\\s*(\\d{1,3})""", RegexOption.IGNORE_CASE).find(command)',
      '        if (scroll == null) {',
      '            scroll = Regex("""(\\d{1,3})\\s*(?:video|វីដេអូ)""", RegexOption.IGNORE_CASE).find(command)',
      '        }',
      '        if (scroll != null) {',
      '            val count = scroll.groupValues[1].toIntOrNull() ?: 20',
      '            steps.add(Step("scroll", "", count))',
      '        }',
      '        return steps',
      '    }',
      '',
      '    private fun parseJson(text: String): List<Step> {',
      '        val steps = mutableListOf<Step>()',
      '        val start = text.indexOf(\'{\')',
      '        val end = text.lastIndexOf(\'}\')',
      '        if (start < 0 || end <= start) return steps',
      '        try {',
      '            val array = JSONObject(text.substring(start, end + 1)).optJSONArray("steps")',
      '                ?: return steps',
      '            for (i in 0 until array.length()) {',
      '                val item = array.optJSONObject(i) ?: continue',
      '                val action = item.optString("action").lowercase()',
      '                if (action.isEmpty()) continue',
      '                steps.add(Step(action, item.optString("target"), item.optInt("count", 0)))',
      '            }',
      '        } catch (e: Exception) {',
      '            steps.clear()',
      '        }',
      '        return steps',
      '    }',
      '',
      '    private fun resolve(context: Context, target: String): String? {',
      '        val query = target.trim().lowercase()',
      '        if (query.isEmpty()) return null',
      '        if (query.contains("tiktok") || query.contains("tik tok")) {',
      '            for (pkg in TIKTOK) if (installed(context, pkg)) return pkg',
      '        }',
      '        if (installed(context, query)) return query',
      '        val pm = context.packageManager',
      '        var best: String? = null',
      '        for (app in pm.getInstalledApplications(PackageManager.GET_META_DATA)) {',
      '            if (app.packageName == context.packageName) continue',
      '            val label = pm.getApplicationLabel(app).toString().lowercase()',
      '            if (label == query) return app.packageName',
      '            if (best == null && label.contains(query)) best = app.packageName',
      '        }',
      '        return best',
      '    }',
      '',
      '    private fun installed(context: Context, pkg: String): Boolean = try {',
      '        context.packageManager.getPackageInfo(pkg, 0) != null',
      '    } catch (e: Exception) {',
      '        false',
      '    }',
      '}',
      ''
    ].join('\n');
  }

  return { groqClientKt: groqClientKt, agentRunnerKt: agentRunnerKt };
});
