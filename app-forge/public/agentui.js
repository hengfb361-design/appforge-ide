/* AI Phone UI sources for the AppForge generator: the accessibility hands with
   tap-by-text, typing and screen reading, plus the chat panel. Kept apart from
   agent.js because the Kotlin here is long and the edit budget per call small;
   gen.js falls back to its simpler OverlayService when this file is missing. */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  root.AppForgeAgentUI = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function agentAccessibilityKt(c) {
    return [
      'package ' + c.pkg,
      '',
      'import android.accessibilityservice.AccessibilityService',
      'import android.accessibilityservice.GestureDescription',
      'import android.content.Intent',
      'import android.graphics.Bitmap',
      'import android.graphics.Path',
      'import android.graphics.Rect',
      'import android.os.Build',
      'import android.os.Bundle',
      'import android.util.Base64',
      'import android.view.accessibility.AccessibilityEvent',
      'import android.view.accessibility.AccessibilityNodeInfo',
      'import java.io.ByteArrayOutputStream',
      'import java.util.concurrent.CountDownLatch',
      'import java.util.concurrent.Executors',
      'import java.util.concurrent.TimeUnit',
      '',
      '/** The hands of the agent: open a package, tap by text, type, swipe, read',
      '    the screen, and the global actions. */',
      'class AgentAccessibilityService : AccessibilityService() {',
      '    override fun onServiceConnected() {',
      '        super.onServiceConnected()',
      '        instance = this',
      '    }',
      '',
      '    override fun onAccessibilityEvent(event: AccessibilityEvent?) {}',
      '',
      '    override fun onInterrupt() {}',
      '',
      '    override fun onDestroy() {',
      '        if (instance === this) instance = null',
      '        super.onDestroy()',
      '    }',
      '',
      '    fun screenSize(): Pair<Int, Int> {',
      '        val metrics = resources.displayMetrics',
      '        return Pair(metrics.widthPixels, metrics.heightPixels)',
      '    }',
      '',
      '    fun openApp(pkg: String): Boolean {',
      '        val intent = packageManager.getLaunchIntentForPackage(pkg) ?: return false',
      '        intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)',
      '        startActivity(intent)',
      '        return true',
      '    }',
      '',
      '    fun swipeUp(): Boolean = swipe(0.78f, 0.22f)',
      '',
      '    fun swipeDown(): Boolean = swipe(0.25f, 0.75f)',
      '',
      '    private fun swipe(from: Float, to: Float): Boolean {',
      '        val metrics = resources.displayMetrics',
      '        val x = metrics.widthPixels / 2f',
      '        val path = Path().apply {',
      '            moveTo(x, metrics.heightPixels * from)',
      '            lineTo(x, metrics.heightPixels * to)',
      '        }',
      '        val gesture = GestureDescription.Builder()',
      '            .addStroke(GestureDescription.StrokeDescription(path, 0, 300))',
      '            .build()',
      '        return dispatchGesture(gesture, null, null)',
      '    }',
      '',
      '    fun tapAt(x: Int, y: Int): Boolean {',
      '        val path = Path().apply { moveTo(x.toFloat(), y.toFloat()) }',
      '        val gesture = GestureDescription.Builder()',
      '            .addStroke(GestureDescription.StrokeDescription(path, 0, 80))',
      '            .build()',
      '        return dispatchGesture(gesture, null, null)',
      '    }',
      '',
      '    /** Clicks the node whose text or description contains the words. */',
      '    fun tapText(query: String): Boolean {',
      '        val wanted = query.trim().lowercase()',
      '        if (wanted.isEmpty()) return false',
      '        val node = find(wanted) ?: return false',
      '        var target: AccessibilityNodeInfo? = node',
      '        while (target != null && !target.isClickable) target = target.parent',
      '        if (target != null && target.performAction(AccessibilityNodeInfo.ACTION_CLICK)) return true',
      '        val rect = Rect()',
      '        node.getBoundsInScreen(rect)',
      '        if (rect.width() <= 0 || rect.height() <= 0) return false',
      '        return tapAt(rect.centerX(), rect.centerY())',
      '    }',
      '',
      '    fun typeText(text: String): Boolean {',
      '        val frame = rootInActiveWindow ?: return false',
      '        var node = frame.findFocus(AccessibilityNodeInfo.FOCUS_INPUT)',
      '        if (node == null) node = firstEditable(frame, 0)',
      '        if (node == null) return false',
      '        node.performAction(AccessibilityNodeInfo.ACTION_FOCUS)',
      '        val args = Bundle()',
      '        args.putCharSequence(AccessibilityNodeInfo.ACTION_ARGUMENT_SET_TEXT_CHARSEQUENCE, text)',
      '        return node.performAction(AccessibilityNodeInfo.ACTION_SET_TEXT, args)',
      '    }',
      '',
      '    fun pressEnter(): Boolean {',
      '        val frame = rootInActiveWindow ?: return false',
      '        val focused = frame.findFocus(AccessibilityNodeInfo.FOCUS_INPUT)',
      '        if (focused != null && Build.VERSION.SDK_INT >= 30) {',
      '            if (focused.performAction(AccessibilityNodeInfo.AccessibilityAction.ACTION_IME_ENTER.id)) {',
      '                return true',
      '            }',
      '        }',
      '        return tapText("search") || tapText("ស្វែងរក")',
      '    }',
      '',
      '    /** What the user sees: visible texts of the other windows only. */',
      '    fun screenText(): String {',
      '        val frame = rootInActiveWindow ?: return ""',
      '        val parts = mutableListOf<String>()',
      '        walk(frame, 0) { node ->',
      '            val text = (node.text ?: node.contentDescription)?.toString()?.trim().orEmpty()',
      '            if (text.length > 1 && parts.size < 90 && !parts.contains(text)) parts.add(text)',
      '        }',
      '        return parts.joinToString(" · ").take(1200)',
      '    }',
      '',
      '    private fun find(wanted: String): AccessibilityNodeInfo? {',
      '        val frame = rootInActiveWindow ?: return null',
      '        var found: AccessibilityNodeInfo? = null',
      '        walk(frame, 0) { node ->',
      '            if (found != null) return@walk',
      '            val text = (node.text ?: node.contentDescription)?.toString()?.lowercase().orEmpty()',
      '            if (text.isNotEmpty() && text.contains(wanted)) found = node',
      '        }',
      '        return found',
      '    }',
      '',
      '    private fun firstEditable(node: AccessibilityNodeInfo, depth: Int): AccessibilityNodeInfo? {',
      '        if (depth > 30) return null',
      '        if (node.isEditable) return node',
      '        for (i in 0 until node.childCount) {',
      '            val child = node.getChild(i) ?: continue',
      '            val hit = firstEditable(child, depth + 1)',
      '            if (hit != null) return hit',
      '        }',
      '        return null',
      '    }',
      '',
      '    private fun walk(node: AccessibilityNodeInfo, depth: Int, visit: (AccessibilityNodeInfo) -> Unit) {',
      '        if (depth > 40) return',
      '        if (node.packageName?.toString() != packageName) visit(node)',
      '        for (i in 0 until node.childCount) {',
      '            val child = node.getChild(i) ?: continue',
      '            walk(child, depth + 1, visit)',
      '        }',
      '    }',
      '',
      '    fun back(): Boolean = performGlobalAction(GLOBAL_ACTION_BACK)',
      '',
      '    fun home(): Boolean = performGlobalAction(GLOBAL_ACTION_HOME)',
      '',
      '    fun recents(): Boolean = performGlobalAction(GLOBAL_ACTION_RECENTS)',
      '',
      '    fun notifications(): Boolean = performGlobalAction(GLOBAL_ACTION_NOTIFICATIONS)',
      '',
      '    fun quickSettings(): Boolean = performGlobalAction(GLOBAL_ACTION_QUICK_SETTINGS)',
      '',
      '    /** Captures the current screen as a small JPEG, base64-encoded, for vision. */',
      '    fun screenshotBase64(maxWidth: Int = 720): String? {',
      '        if (Build.VERSION.SDK_INT < 30) return null',
      '        val latch = CountDownLatch(1)',
      '        var result: String? = null',
      '        try {',
      '            takeScreenshot(0, Executors.newSingleThreadExecutor(), object : TakeScreenshotCallback {',
      '                override fun onSuccess(screenshot: ScreenshotResult) {',
      '                    try {',
      '                        val buffer = screenshot.hardwareBuffer',
      '                        val bitmap = Bitmap.wrapHardwareBuffer(buffer, screenshot.colorSpace)',
      '                        if (bitmap != null) {',
      '                            val software = bitmap.copy(Bitmap.Config.ARGB_8888, false)',
      '                            bitmap.recycle()',
      '                            buffer.close()',
      '                            val scaled = if (software.width > maxWidth) {',
      '                                val ratio = maxWidth.toFloat() / software.width',
      '                                Bitmap.createScaledBitmap(software, maxWidth, (software.height * ratio).toInt(), true)',
      '                            } else {',
      '                                software',
      '                            }',
      '                            val stream = ByteArrayOutputStream()',
      '                            scaled.compress(Bitmap.CompressFormat.JPEG, 60, stream)',
      '                            if (scaled !== software) scaled.recycle()',
      '                            software.recycle()',
      '                            result = Base64.encodeToString(stream.toByteArray(), Base64.NO_WRAP)',
      '                        } else {',
      '                            buffer.close()',
      '                        }',
      '                    } catch (e: Exception) {',
      '                        result = null',
      '                    }',
      '                    latch.countDown()',
      '                }',
      '',
      '                override fun onFailure(errorCode: Int) {',
      '                    latch.countDown()',
      '                }',
      '            })',
      '        } catch (e: Exception) {',
      '            return null',
      '        }',
      '        latch.await(5, TimeUnit.SECONDS)',
      '        return result',
      '    }',
      '',
      '    fun currentPackage(): String = rootInActiveWindow?.packageName?.toString().orEmpty()',
      '',
      '    fun lockScreen(): Boolean = performGlobalAction(GLOBAL_ACTION_LOCK_SCREEN)',
      '',
      '    companion object {',
      '        @Volatile',
      '        var instance: AgentAccessibilityService? = null',
      '            private set',
      '    }',
      '}',
      ''
    ].join('\n');
  }

  function overlayKt(c) {
    return [
      'package ' + c.pkg,
      '',
      'import android.app.Notification',
      'import android.app.NotificationChannel',
      'import android.app.NotificationManager',
      'import android.app.Service',
      'import android.content.Intent',
      'import android.graphics.Color',
      'import android.graphics.PixelFormat',
      'import android.graphics.Typeface',
      'import android.os.Build',
      'import android.os.Handler',
      'import android.os.IBinder',
      'import android.os.Looper',
      'import android.provider.Settings',
      'import android.view.Gravity',
      'import android.view.View',
      'import android.view.ViewGroup',
      'import android.view.WindowManager',
      'import android.view.inputmethod.EditorInfo',
      'import android.widget.Button',
      'import android.widget.EditText',
      'import android.widget.LinearLayout',
      'import android.widget.ScrollView',
      'import android.widget.TextView',
      'import androidx.core.app.NotificationCompat',
      '',
      '/** Floating AI bubble that opens a chat panel above every app. */',
      'class OverlayService : Service() {',
      '    private var manager: WindowManager? = null',
      '    private var bubble: TextView? = null',
      '    private var panel: LinearLayout? = null',
      '    private var logView: TextView? = null',
      '    private var logScrollView: ScrollView? = null',
      '    private val ui = Handler(Looper.getMainLooper())',
      '    private val density: Float get() = resources.displayMetrics.density',
      '',
      '    override fun onBind(intent: Intent?): IBinder? = null',
      '',
      '    override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {',
      '        startForeground(NOTIFICATION_ID, notification())',
      '        AgentLog.sink = { line -> append(line) }',
      '        if (bubble == null && panel == null) showBubble()',
      '        return START_STICKY',
      '    }',
      '',
      '    private fun notification(): Notification {',
      '        val nm = getSystemService(NotificationManager::class.java)',
      '        if (Build.VERSION.SDK_INT >= 26) {',
      '            nm.createNotificationChannel(',
      '                NotificationChannel(CHANNEL_ID, "AI Phone", NotificationManager.IMPORTANCE_LOW)',
      '            )',
      '        }',
      '        return NotificationCompat.Builder(this, CHANNEL_ID)',
      '            .setContentTitle("AI Phone")',
      '            .setContentText("ចុចប៊ូប AI ដើម្បីសន្ទនា ឬបញ្ជា")',
      '            .setSmallIcon(android.R.drawable.ic_menu_compass)',
      '            .setOngoing(true)',
      '            .build()',
      '    }',
      '',
      '    private fun dp(value: Int): Int = (value * density).toInt()',
      '',
      '    @Suppress("DEPRECATION")',
      '    private fun overlayType(): Int =',
      '        if (Build.VERSION.SDK_INT >= 26) WindowManager.LayoutParams.TYPE_APPLICATION_OVERLAY',
      '        else WindowManager.LayoutParams.TYPE_PHONE',
      '',
      '    private fun params(focusable: Boolean): WindowManager.LayoutParams {',
      '        val p = WindowManager.LayoutParams(',
      '            WindowManager.LayoutParams.WRAP_CONTENT,',
      '            WindowManager.LayoutParams.WRAP_CONTENT,',
      '            overlayType(),',
      '            WindowManager.LayoutParams.FLAG_NOT_TOUCH_MODAL or WindowManager.LayoutParams.FLAG_LAYOUT_IN_SCREEN,',
      '            PixelFormat.TRANSLUCENT',
      '        )',
      '        if (!focusable) p.flags = p.flags or WindowManager.LayoutParams.FLAG_NOT_FOCUSABLE',
      '        p.gravity = Gravity.TOP or Gravity.START',
      '        p.x = dp(8)',
      '        p.y = dp(96)',
      '        p.softInputMode = WindowManager.LayoutParams.SOFT_INPUT_ADJUST_RESIZE',
      '        return p',
      '    }',
      '',
      '    private fun showBubble() {',
      '        if (!Settings.canDrawOverlays(this)) {',
      '            stopSelf()',
      '            return',
      '        }',
      '        val wm = getSystemService(WINDOW_SERVICE) as WindowManager',
      '        manager = wm',
      '        val view = TextView(this).apply {',
      '            text = "AI"',
      '            textSize = 15f',
      '            typeface = Typeface.DEFAULT_BOLD',
      '            gravity = Gravity.CENTER',
      '            setTextColor(Color.parseColor("#08131F"))',
      '            setBackgroundColor(Color.parseColor("#FFC24B"))',
      '            setPadding(dp(12), dp(12), dp(12), dp(12))',
      '            setOnClickListener { openPanel() }',
      '        }',
      '        wm.addView(view, params(false))',
      '        bubble = view',
      '    }',
      '',
      '    private fun openPanel() {',
      '        val wm = manager ?: return',
      '        bubble?.let { view -> runCatching { wm.removeView(view) } }',
      '        bubble = null',
      '',
      '        val root = LinearLayout(this).apply {',
      '            orientation = LinearLayout.VERTICAL',
      '            setBackgroundColor(Color.parseColor("#F2081118"))',
      '            setPadding(dp(12), dp(10), dp(12), dp(10))',
      '        }',
      '        root.layoutParams = LinearLayout.LayoutParams(dp(320), LinearLayout.LayoutParams.WRAP_CONTENT)',
      '',
      '        val header = LinearLayout(this).apply {',
      '            orientation = LinearLayout.HORIZONTAL',
      '            gravity = Gravity.CENTER_VERTICAL',
      '        }',
      '        val title = TextView(this).apply {',
      '            text = "AI Phone · Groq"',
      '            textSize = 15f',
      '            typeface = Typeface.DEFAULT_BOLD',
      '            setTextColor(Color.parseColor("#FFD37A"))',
      '        }',
      '        header.addView(title, LinearLayout.LayoutParams(0, LinearLayout.LayoutParams.WRAP_CONTENT, 1f))',
      '',
      '        val clear = TextView(this).apply {',
      '            text = "🗑"',
      '            textSize = 13f',
      '            setTextColor(Color.parseColor("#9FB3C8"))',
      '            setPadding(dp(8), 0, dp(8), 0)',
      '            setOnClickListener {',
      '                AgentChat.clear()',
      '                logView?.text = ""',
      '                append("✨ សន្ទនាថ្មី")',
      '            }',
      '        }',
      '        header.addView(clear)',
      '',
      '        val close = TextView(this).apply {',
      '            text = "✕"',
      '            textSize = 15f',
      '            setTextColor(Color.parseColor("#E6EDF3"))',
      '            setPadding(dp(10), 0, dp(2), 0)',
      '            setOnClickListener { closePanel() }',
      '        }',
      '        header.addView(close)',
      '        root.addView(header)',
      '',
      '        val log = TextView(this).apply {',
      '            textSize = 12f',
      '            setTextColor(Color.parseColor("#CDE7FF"))',
      '            setPadding(dp(4), dp(6), dp(4), dp(6))',
      '        }',
      '        val logScroll = ScrollView(this).apply {',
      '            setBackgroundColor(Color.parseColor("#08131F"))',
      '            addView(',
      '                log,',
      '                ViewGroup.LayoutParams(',
      '                    ViewGroup.LayoutParams.MATCH_PARENT,',
      '                    ViewGroup.LayoutParams.WRAP_CONTENT',
      '                )',
      '            )',
      '        }',
      '        root.addView(',
      '            logScroll,',
      '            LinearLayout.LayoutParams(LinearLayout.LayoutParams.MATCH_PARENT, dp(250))',
      '        )',
      '',
      '        val row = LinearLayout(this).apply {',
      '            orientation = LinearLayout.HORIZONTAL',
      '            gravity = Gravity.CENTER_VERTICAL',
      '        }',
      '        val input = EditText(this).apply {',
      '            hint = "សួរ AI ឬបញ្ជា… ឧ. បើក tiktok អូស 20"',
      '            textSize = 13f',
      '            isSingleLine = true',
      '            imeOptions = EditorInfo.IME_ACTION_SEND',
      '            setTextColor(Color.parseColor("#E6EDF3"))',
      '            setHintTextColor(Color.parseColor("#7A889B"))',
      '        }',
      '        row.addView(input, LinearLayout.LayoutParams(0, LinearLayout.LayoutParams.WRAP_CONTENT, 1f))',
      '        val send = Button(this).apply { text = "➤" }',
      '        row.addView(send)',
      '        root.addView(row)',
      '',
      '        wm.addView(root, params(true))',
      '        panel = root',
      '        logView = log',
      '        logScrollView = logScroll',
      '',
      '        send.setOnClickListener { submit(input, log) }',
      '        input.setOnEditorActionListener { _, actionId, _ ->',
      '            if (actionId == EditorInfo.IME_ACTION_SEND) {',
      '                submit(input, log)',
      '                true',
      '            } else {',
      '                false',
      '            }',
      '        }',
      '    }',
      '',
      '    private fun submit(input: EditText, log: TextView) {',
      '        val command = input.text.toString().trim()',
      '        if (command.isEmpty()) return',
      '        input.setText("")',
      '        if (log.text.isEmpty()) log.text = "👤 " + command else log.append("\\n👤 " + command)',
      '        scrollSoon()',
      '        AgentRunner.run(applicationContext, command) { line -> append(line) }',
      '    }',
      '',
      '    private fun closePanel() {',
      '        panel?.let { view -> manager?.let { runCatching { it.removeView(view) } } }',
      '        panel = null',
      '        logView = null',
      '        logScrollView = null',
      '        showBubble()',
      '    }',
      '',
      '    private fun scrollSoon() {',
      '        ui.post { logScrollView?.fullScroll(View.FOCUS_DOWN) }',
      '    }',
      '',
      '    private fun append(line: String) {',
      '        ui.post {',
      '            val view = logView ?: return@post',
      '            if (view.text.isEmpty()) view.text = line else view.append("\\n" + line)',
      '            scrollSoon()',
      '        }',
      '    }',
      '',
      '    override fun onDestroy() {',
      '        AgentLog.sink = null',
      '        bubble?.let { view -> manager?.let { runCatching { it.removeView(view) } } }',
      '        panel?.let { view -> manager?.let { runCatching { it.removeView(view) } } }',
      '        bubble = null',
      '        panel = null',
      '        logView = null',
      '        logScrollView = null',
      '        super.onDestroy()',
      '    }',
      '',
      '    companion object {',
      '        private const val CHANNEL_ID = "ai_phone"',
      '        private const val NOTIFICATION_ID = 77',
      '    }',
      '}',
      ''
    ].join('\n');
  }

  return { agentAccessibilityKt: agentAccessibilityKt, overlayKt: overlayKt };
});
